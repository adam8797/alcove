using System.Collections;
using System.Reflection;

namespace Alcove.Development;

/// <summary>The harness convention for development plugins: Alcove parses, the app decides.</summary>
public static class DevelopmentPluginExtensions
{
    /// <summary>The command-line option naming a development plugin's build output folder (repeatable).</summary>
    public const string CommandLineOption = "--alcove-dev-plugin";

    /// <summary>The environment variable listing development plugins' build output folders, separated by <see cref="Path.PathSeparator"/>.</summary>
    public const string EnvironmentVariable = "ALCOVE_DEV_PLUGINS";

    /// <summary>
    /// Adds the development plugins a harness was started with to <see cref="PluginHostOptions.DevelopmentPlugins"/>:
    /// every <c>--alcove-dev-plugin &lt;path&gt;</c> (or <c>--alcove-dev-plugin=&lt;path&gt;</c>) in <paramref name="args"/>,
    /// the folders in the <c>ALCOVE_DEV_PLUGINS</c> environment variable, and the entry assembly's
    /// <see cref="AlcoveDevelopmentPluginAttribute"/>s (generated by <c>PluginUnderTest</c>).
    /// </summary>
    /// <remarks>
    /// Nothing loads development plugins unless the app calls this (or fills the list itself): call it only from a
    /// harness, or behind an explicit flag, never on the app's normal startup path. Paths are made absolute against the
    /// current directory; a folder named twice is added once. The options are left in <paramref name="args"/>.
    /// </remarks>
    /// <param name="options">The host options to add to.</param>
    /// <param name="args">The command-line arguments.</param>
    /// <param name="environment">The environment variables, e.g. <see cref="Environment.GetEnvironmentVariables()"/>; <see langword="null"/> to skip them.</param>
    /// <returns>The development plugins added.</returns>
    /// <exception cref="ArgumentException"><c>--alcove-dev-plugin</c> is the last argument, with no path after it.</exception>
    public static IReadOnlyList<DevelopmentPlugin> AddDevelopmentPluginsFrom(this PluginHostOptions options, IReadOnlyList<string> args, IDictionary? environment) =>
        AddDevelopmentPluginsFrom(options, args, environment, Assembly.GetEntryAssembly());

    /// <summary><see cref="AddDevelopmentPluginsFrom(PluginHostOptions, IReadOnlyList{string}, IDictionary?)"/> with a given entry assembly (tests).</summary>
    internal static IReadOnlyList<DevelopmentPlugin> AddDevelopmentPluginsFrom(this PluginHostOptions options, IReadOnlyList<string> args, IDictionary? environment, Assembly? entryAssembly)
    {
        ArgumentNullException.ThrowIfNull(options);
        ArgumentNullException.ThrowIfNull(args);
        var seen = options.DevelopmentPlugins.Select(p => Normalize(p.OutputDirectory)).ToHashSet(PathComparer);
        var added = new List<DevelopmentPlugin>();
        foreach (var plugin in Read(args, environment, entryAssembly))
        {
            if (seen.Add(Normalize(plugin.OutputDirectory)))
            {
                options.DevelopmentPlugins.Add(plugin);
                added.Add(plugin);
            }
        }

        return added;
    }

    /// <summary>The development plugins named by the arguments, the environment and the entry assembly, in that order.</summary>
    internal static IEnumerable<DevelopmentPlugin> Read(IReadOnlyList<string> args, IDictionary? environment, Assembly? entryAssembly)
    {
        for (var i = 0; i < args.Count; i++)
        {
            var arg = args[i];
            if (string.Equals(arg, CommandLineOption, StringComparison.Ordinal))
            {
                if (i + 1 >= args.Count || string.IsNullOrWhiteSpace(args[i + 1]))
                {
                    throw new ArgumentException($"{CommandLineOption} needs the path of a plugin's build output folder after it.", nameof(args));
                }

                yield return new DevelopmentPlugin(Path.GetFullPath(args[++i]));
            }
            else if (arg.StartsWith(CommandLineOption + "=", StringComparison.Ordinal))
            {
                var value = arg[(CommandLineOption.Length + 1)..];
                if (string.IsNullOrWhiteSpace(value))
                {
                    throw new ArgumentException($"{CommandLineOption}= needs the path of a plugin's build output folder.", nameof(args));
                }

                yield return new DevelopmentPlugin(Path.GetFullPath(value));
            }
        }

        if (environment?[EnvironmentVariable] is string list)
        {
            foreach (var path in list.Split(Path.PathSeparator, StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries))
            {
                yield return new DevelopmentPlugin(Path.GetFullPath(path));
            }
        }

        if (entryAssembly is not null)
        {
            foreach (var attribute in entryAssembly.GetCustomAttributes<AlcoveDevelopmentPluginAttribute>())
            {
                if (!string.IsNullOrWhiteSpace(attribute.OutputDirectory))
                {
                    yield return new DevelopmentPlugin(Path.GetFullPath(attribute.OutputDirectory), attribute.ProjectPath);
                }
            }
        }
    }

    private static StringComparer PathComparer => OperatingSystem.IsWindows() || OperatingSystem.IsMacOS() ? StringComparer.OrdinalIgnoreCase : StringComparer.Ordinal;

    private static string Normalize(string path) => Path.TrimEndingDirectorySeparator(Path.GetFullPath(path));
}
